package ru.player_skill.weatherage.config;

/**
 * Режим работы мира. Определяет, как плагин реагирует на погоду в конкретном мире.
 * Это основа всей логики из конфига.
 */
public enum WorldMode {
    /**
     * Мир НЕ в whitelist.
     * Погода всегда солнечная. Никакие команды (даже ванильные /weather)
     * не могут её изменить. Все события смены погоды будут отменяться.
     */
    ALWAYS_SUN,

    /**
     * Мир в whitelist, но без каких-либо настроек в конфиге.
     * Работает обычный ванильный цикл погоды Майнкрафт.
     * Плагин не вмешивается, сообщений не пишет, команд не выполняет.
     */
    VANILLA,

    /**
     * Мир в whitelist + есть секция vanilla-weather.
     * Ванильный цикл погоды сохраняется, но при смене погоды
     * плагин показывает кастомные сообщения и выполняет команды.
     * Тут работает защита от дублей (storm-waiting-ticks).
     */
    VANILLA_WITH_MESSAGES,

    /**
     * Мир в whitelist + есть секция custom-weather.
     * Погода подчиняется кастомному циклу плагина (шансы, длительности).
     * Ванильный цикл игнорируется.
     */
    CUSTOM
}
